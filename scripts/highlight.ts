// Writes src/ui/highlight/precompiled.ts: each language's regexes as literals, so an AOT
// build compiles them to machine code. Run it after changing a language:
//   bun scripts/highlight.ts
// test/highlight.test.ts fails while the file is out of date.

import { join } from "node:path";
import { build } from "../src/ui/highlight/engine";
import { LANGUAGES } from "../src/ui/highlight/languages";

const OUT = join(import.meta.dir, "..", "src/ui/highlight/precompiled.ts");
const literal = (regex: RegExp) => `/${regex.source}/${regex.flags}`;

const entries = LANGUAGES.map((language) => {
  const { scanner, closers, pieces } = build(language);
  return [
    `  ${JSON.stringify(language.names[0])}: {`,
    `    scanner: ${literal(scanner)},`,
    `    closers: [${closers.map(literal).join(", ")}],`,
    `    pieces: ${JSON.stringify(pieces)},`,
    "  },",
  ].join("\n");
});

await Bun.write(
  OUT,
  [
    "// Generated by scripts/highlight.ts from languages/. Do not edit; run `bun scripts/highlight.ts`.",
    'import type { Patterns } from "./engine";',
    "",
    "export const PRECOMPILED: Record<string, Patterns> = {",
    ...entries,
    "};",
    "",
  ].join("\n"),
);
// Formatted like the rest of src, so `bun run fmt` leaves it unchanged.
const fmt = Bun.spawnSync([process.execPath, "fmt", "--no-script", OUT], { stdout: "ignore", stderr: "pipe" });
if (fmt.exitCode !== 0) {
  process.stderr.write(fmt.stderr);
  process.exit(fmt.exitCode ?? 1);
}
console.log(`wrote ${LANGUAGES.length} languages to ${OUT}`);
